# Python Fundamentals
# Topic: Operators

x = 10
y = 3

print("Addition:", x + y)
print("Subtraction:", x - y)
print("Multiplication:", x * y)
print("Division:", x / y)
print("Modulus:", x % y)
print("Exponentiation:", x ** y)

print("10 > 3:", x > y)
print("10 < 3:", x < y)
print("10 == 3:", x == y)
